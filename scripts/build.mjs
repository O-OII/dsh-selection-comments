import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const locales = Object.fromEntries(['en', 'zh'].map(code => [code, JSON.parse(fs.readFileSync(path.join(root, 'locale', code + '.json'), 'utf8'))]))
const keys = Object.keys(locales.en).sort()
if (JSON.stringify(keys) !== JSON.stringify(Object.keys(locales.zh).sort())) throw new Error('Locale keys differ')
for (const key of keys) {
  const placeholders = value => [...value.matchAll(/\{(\w+)\}/g)].map(match => match[1]).sort().join(',')
  if (placeholders(locales.en[key]) !== placeholders(locales.zh[key])) throw new Error('Locale placeholders differ: ' + key)
}
const source = fs.readFileSync(path.join(root, 'src/client.js'), 'utf8')
if (source.split('__DSH_COMMENT_MESSAGES__').length !== 2) throw new Error('Expected one message injection marker')
const output = '// Generated by scripts/build.mjs; edit src/client.js and locale/*.json.\n' + source.replace('__DSH_COMMENT_MESSAGES__', JSON.stringify(locales))
const file = path.join(root, 'lib/client.js')
if (process.argv.includes('--check')) {
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== output) throw new Error('Generated client is stale; run npm run build')
} else {
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, output, 'utf8')
}
console.log(process.argv.includes('--check') ? 'Generated bundle and locale parity verified' : 'Built dependency-free client bundle')
